"""The numpy port reproduces the original llops-backed code.

tests/fixtures/reference.npz was generated by tests/reference/make_reference.py
from the pre-port code; see that script for provenance and the llops patches it
needed.
"""
import os
import tempfile

import numpy as np
import pytest

import htdeblur
import htdeblur.analysis  # noqa: F401
import htdeblur.mddataset  # noqa: F401
import harness

FIXTURE = os.path.join(os.path.dirname(__file__), 'fixtures', 'reference.npz')


@pytest.fixture(scope='module')
def outputs():
    out = {}
    with tempfile.TemporaryDirectory() as tmp:
        harness.case_blurkernel(htdeblur, out)
        harness.case_analysis(htdeblur, out)
        harness.case_optics(htdeblur, out)
        harness.case_registration(htdeblur, out)
        path = harness.case_dataset(htdeblur, out, tmp)
        harness.case_recon_init(htdeblur, out, path)
        harness.case_recon_solve(htdeblur, out, path)
        harness.case_mddataset_processing(htdeblur, out, path)
    return out


_ref = np.load(FIXTURE)


@pytest.mark.parametrize('key', sorted(_ref.files))
def test_matches_reference(outputs, key):
    expected = _ref[key]
    assert key in outputs, 'case did not produce %s' % key
    actual = np.asarray(outputs[key])
    assert actual.shape == expected.shape
    if expected.dtype.kind == 'U':
        assert (actual == expected).all()
    else:
        scale = max(1.0, float(np.nanmax(np.abs(expected)))) if expected.size else 1.0
        np.testing.assert_allclose(actual, expected, rtol=1e-5, atol=1e-6 * scale, equal_nan=True)
